import fs from 'node:fs'
import path from 'node:path'
import { normalizeTopic, auditNeedsReview, auditDataQualityFlags } from './topic-aliases.mjs'

const EBAS_ROOT = 'C:\\Projects\\eba-wiki\\docs\\ebas'
const OUTPUT_DIR = 'C:\\Projects\\eba-wiki\\docs\\.vitepress\\generated'
const OUTPUT_FILE = 'C:\\Projects\\eba-wiki\\docs\\.vitepress\\generated\\topic-list.mjs'

function getAllMarkdownFiles(dir) {
  const entries = fs.readdirSync(dir, { withFileTypes: true })
  const files = []

  for (const entry of entries) {
    // Archived agreements (docs/ebas/archive/<slug>/) are excluded from the
    // live Pagefind index entirely — see patch-pagefind.mjs, which strips
    // filter spans and marks archived pages data-pagefind-ignore. A topic
    // that only exists inside an archived agreement would therefore appear
    // in this dropdown but return zero results every time it's selected.
    // Generate-TopicsPage.ps1 already excludes this folder for the same
    // reason ("archived agreements excluded") — this matches that scope.
    if (entry.isDirectory() && entry.name.toLowerCase() === 'archive') {
      continue
    }

    const fullPath = path.join(dir, entry.name)

    if (entry.isDirectory()) {
      files.push(...getAllMarkdownFiles(fullPath))
      continue
    }

    if (entry.isFile() && fullPath.toLowerCase().endsWith('.md')) {
      files.push(fullPath)
    }
  }

  return files
}

function getFrontMatterBlock(content) {
  const match = content.match(/^---\r?\n([\s\S]*?)\r?\n---/)
  return match ? match[1] : null
}

function stripWrappingQuotes(value) {
  const trimmed = value.trim()

  if (
    (trimmed.startsWith("'") && trimmed.endsWith("'")) ||
    (trimmed.startsWith('"') && trimmed.endsWith('"'))
  ) {
    return trimmed.slice(1, -1).trim()
  }

  return trimmed
}

function parseInlineTopicArray(value) {
  const trimmed = value.trim()

  if (!trimmed.startsWith('[') || !trimmed.endsWith(']')) {
    return []
  }

  const inner = trimmed.slice(1, -1).trim()

  if (!inner) {
    return []
  }

  return inner
    .split(',')
    .map(part => stripWrappingQuotes(part))
    .filter(Boolean)
}

function getTopicsFromFrontMatter(frontMatter) {
  const lines = frontMatter.split(/\r?\n/)
  const topics = []
  let inTopicsBlock = false

  for (const line of lines) {
    if (!inTopicsBlock) {
      const inlineMatch = line.match(/^\s*topics\s*:\s*(.+?)\s*$/)

      if (inlineMatch) {
        const value = inlineMatch[1].trim()

        if (value) {
          return parseInlineTopicArray(value)
        }

        inTopicsBlock = true
      }

      continue
    }

    const itemMatch = line.match(/^\s*-\s*(.+?)\s*$/)

    if (itemMatch) {
      const topic = stripWrappingQuotes(itemMatch[1])

      if (topic) {
        topics.push(topic)
      }

      continue
    }

    if (/^\s*$/.test(line)) {
      continue
    }

    if (/^\S/.test(line) || /^[A-Za-z0-9_-]+\s*:/.test(line)) {
      break
    }

    break
  }

  return topics
}

function collectUniqueTopics() {
  const files = getAllMarkdownFiles(EBAS_ROOT)
  const rawTopics = new Set()      // exactly as written in frontmatter — used for the review audit
  const normalizedTopics = new Set() // after applying TOPIC_ALIASES — this is what ships to the dropdown

  for (const file of files) {
    const raw = fs.readFileSync(file, 'utf8')
    const frontMatter = getFrontMatterBlock(raw)

    if (!frontMatter) {
      continue
    }

    for (const topic of getTopicsFromFrontMatter(frontMatter)) {
      rawTopics.add(topic)
      normalizedTopics.add(normalizeTopic(topic))
    }
  }

  return {
    normalized: [...normalizedTopics].sort((a, b) => a.localeCompare(b)),
    raw: [...rawTopics],
  }
}

function writeGeneratedModule(topics) {
  fs.mkdirSync(OUTPUT_DIR, { recursive: true })

  const lines = [
    '// AUTO-GENERATED FILE. DO NOT EDIT MANUALLY.',
    '// Generated by C:\\Projects\\eba-wiki\\docs\\scripts\\Generate-TopicList.mjs',
    '',
    `export const topicList = ${JSON.stringify(topics, null, 2)}`,
    '',
    'export default topicList',
    ''
  ]

  fs.writeFileSync(OUTPUT_FILE, lines.join('\n'), 'utf8')
}

function main() {
  if (!fs.existsSync(EBAS_ROOT)) {
    throw new Error(`EBA content root not found: ${EBAS_ROOT}`)
  }

  const { normalized, raw } = collectUniqueTopics()
  writeGeneratedModule(normalized)

  console.log(`Generated ${normalized.length} topics (from ${raw.length} raw frontmatter values, ${raw.length - normalized.length} merged via topic-aliases.mjs)`)
  console.log(OUTPUT_FILE)

  const stillNeedsReview = auditNeedsReview(raw)
  if (stillNeedsReview.length > 0) {
    console.log('\n⚠️  Topic clusters flagged for human review (not auto-merged):')
    for (const cluster of stillNeedsReview) {
      console.log(`   - [${cluster.present.join(', ')}]`)
      console.log(`     ${cluster.note}`)
    }
    console.log('\n   See topic-aliases.mjs NEEDS_REVIEW for how to resolve these.')
  }

  const dataQualityIssues = auditDataQualityFlags(raw)
  if (dataQualityIssues.length > 0) {
    console.log('\n🚩 Likely data-quality issues (malformed or mistagged topics, NOT duplicates):')
    for (const flag of dataQualityIssues) {
      console.log(`   - [${flag.present.join(', ')}]`)
      console.log(`     ${flag.note}`)
    }
    console.log('\n   These need a source-content fix in the affected .md frontmatter, not an alias merge.')
  }
}

main()
